using SourceLib.Core.Formats.MDL;
using SourceLib.Core.Formats.VPK;
using SourceLib.Tests.GameData;

namespace SourceLib.Tests.Formats;

[Collection("Game")]
public class MDLFormatTests
{
    private readonly IGameDataProvider _games;

    public MDLFormatTests(GameDataFixture games)
    {
        _games = games.Provider;
    }

    [Fact]
    public void Test_Parses_V44_HL2_Cheaple()
    {
        var hl2 = _games.Get(GameId.HalfLife2);
        var hl2MiscVpk = hl2.GetVPK(
            new VPKFormatParser(),
            ["hl2", "hl2_misc_dir.vpk"],
            [
                hl2.GetPath("hl2", "hl2_misc_000.vpk"),
                hl2.GetPath("hl2", "hl2_misc_001.vpk"),
                hl2.GetPath("hl2", "hl2_misc_002.vpk"),
                hl2.GetPath("hl2", "hl2_misc_003.vpk"),
            ]
        );
        var fixtureBytes = hl2MiscVpk.ReadFileAsBytes("models/humans/charple01.mdl");
        var mdlParser = new MDLFormatParser();
        var mdl = mdlParser.Parse(fixtureBytes);
        Assert.Equal(StudioMdlVersion.V44, mdl.Header.Version);
        Assert.Equal("Humans\\Charple01.mdl", mdl.Header.Name);
        Assert.Equal(917997919, mdl.Header.Checksum);
        Assert.True(mdl.Header.Flags.HasFlag(StudioMdlFlags.AutogeneratedHitbox));
        Assert.True(mdl.Header.Flags.HasFlag(StudioMdlFlags.HasShadowLod));
        Assert.Equal(16, mdl.Header.BoneCount);
        Assert.Contains("Charple1_sheet", mdl.Textures.Select(t => t.Name));
        Assert.Equal("models\\Charple\\", mdl.TextureDirectories[0]);
    }
}
